/* ————— خريطة الدماغ: أربعة عشر فصاً وما يفعل كلٌّ منها —————
 *
 * الغرض أن يرى الأب دماغ ابنه لا صندوقاً مغلقاً. الأسماء تشريحية حقيقية،
 * والوظائف هي وظائف الفصوص نفسها في دماغ حقيقي — كل فص هنا يقابل فصاً هناك.
 */

export function BrainMap(props: { lobes: ReadonlyArray<{ name: string; ar: string; role: string }> }) {
  return (
    <div className="panel">
      <div className="card">
        <h2>دماغ زبير</h2>
        <p>
          كل فص وحدة مستقلّة لها وظيفة، والفصوص تتخاطب عبر ناقل واحد. تلف فصٍّ يُفقد وظيفته
          وحدها لا الدماغ كله — كما في الدماغ الحقيقي.
        </p>
        {props.lobes.map((lobe) => (
          <div className="lobe" key={lobe.name}>
            <b>{lobe.ar}</b>
            <span>{lobe.role}</span>
          </div>
        ))}
      </div>

      <div className="card">
        <h2>وظائف بلا مقابل حاسوبي مباشر</h2>
        <p>
          بعض أعضاء الدماغ لا يقابلها في الحاسوب شيء، فأُعطيت مقابلاً هندسياً مكافئاً:
        </p>
        <div className="lobe">
          <b>الجسم الثفني</b>
          <span>ناقل الرسائل بين الفصوص: كل فص يستلم ما يحتاجه ويُسلّم ما ينتجه، ولا يعرف الباقي</span>
        </div>
        <div className="lobe">
          <b>الغدة الصنوبرية</b>
          <span>ساعة النوم والصحو: في النوم تُعاد الذكريات مراراً لتثبّت — وهو ما يفعله دماغك كل ليلة</span>
        </div>
        <div className="lobe">
          <b>النخاع الشوكي</b>
          <span>منفذا الدخل والخرج: حرفك الذي يقرؤه، وكلامه الذي تقرؤه</span>
        </div>
      </div>

      <div className="card">
        <h2>ما لا يفعله زبير</h2>
        <p>
          لن يكتب لك مقالاً ولن يترجم ولن يعرف شيئاً لم تُعلّمه إياه أو يستنتجه من تعليمك. رأى
          نصّك أنت فقط، لا تيرابايتات من نصوص البشرية. من وعدك بغير هذا كذب عليك.
        </p>
      </div>
    </div>
  );
}
