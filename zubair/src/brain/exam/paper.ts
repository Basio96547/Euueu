/* ————— الامتحان المجمَّد —————
 *
 * ٢٨٦ اختبار وحدة تحرس الفصوص، لكنها لا تحرس **السلوك**. وما يضيع في إعادة
 * بناءٍ كبيرة ليس وحدةً تنكسر — بل جوابٌ كان صائباً فصار محتملاً، وتحفّظٌ كان
 * في محلّه فصار جزماً. لا ينكسر شيء، ولا يمرّ اختبارٌ بالأحمر، ويصير زبير أغبى
 * وأنت لا تدري إلا بإحساسك. وذاك أسوأ سبيلٍ لاكتشافه.
 *
 * فهذا امتحانٌ **ثابت**: بنودٌ لا تتغيّر بأجوبتها المرجوّة، يُعاد كما هو قبل كل
 * تغييرٍ وبعده، وتُقارَن النسبة بالنسبة.
 *
 * ———— وشرطان في بنائه ————
 *
 *  ١) كل بندٍ يُعلَّم موضوعاً **لم يُذكر في بندٍ آخر ولا في ميراثه**، فلا يُقاس
 *     بندٌ بما سرّبه إليه بندٌ قبله. والألفاظ المخترعة مقصودة لهذا بعينه.
 *
 *  ٢) أبوابٌ للهلوسة قائمة بذاتها، وهي أهمّ ما في الورقة. والنقد الذي وُلدت
 *     منه دقيق: عشر كلماتٍ مخترعة تقيس **كشف الخارج عن المفردات** لا التعميم
 *     الخطر. والخطر يقع **داخل** ما يعرف:
 *
 *       الاستثناء: «الطائر يطير» ثم «البطريق طائر» — أيجزم أن البطريق يطير؟
 *       السلسلة:   «س ص» و«ص ع» — أيقفز إلى «س ع»؟ وبأي ثقة؟
 *       المعايرة:  ثقةٌ معلنة ٠٫٧ يجب أن تعني: أُصيب سبعين بالمئة من المرات.
 *
 *     ولا يُقاس الثالث ببندٍ واحد بل بالورقة كلها — انظر `calibration` في
 *     `run.ts`.
 */

