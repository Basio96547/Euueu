/* ————— المراجعة: رتبٌ لا أرقام —————
 *
 * قِيس رقمُ ثقة زبير على الامتحان فخرج: حين أصاب ٠٫٦٨، وحين أخطأ ٠٫٦٩. أي أنه
 * **لا يفصل صوابه عن خطئه**، فالترجيح به أسبقيةٌ مكتوبةٌ باليد في ثوبٍ عدديّ.
 *
 * والسبب بيّنٌ في مصدره: الرقم هو `١ − التعارض`، والتعارضُ مجموعٌ موزون فيه
 * ٠٫٤ لِـ«لم أفهم ماذا تريد» و٠٫٢ فقط لِـ«لا أثق بما أعرفه عن هذا». فخُمسٌ
 * واحد منه يخصّ متانة الجواب، وخُمسان يخصّان وضوحَ السؤال — وهما سؤالان
 * مختلفان خُلطا في رقمٍ واحد. ثم إن جدول الملكية جعل الاستخراج حتمياً، فثبّت
 * مركّبَ الأربعين عند قيمةٍ واحدة تقريباً، فسطّح الرقمَ أكثر.
 *
 * فما لا يمكن معايرته يُخرج **رتبةً لا رقماً**. والرتبة هنا مبنيّةٌ على ما
 * يُعَدّ ويُرى، لا على مجموعٍ موزون: من علّمها؟ وكم مرة؟ وهل نوزعت؟
 *
 * ولا يُترجَّح بالرتبة بين دعاوى متنافسة — فلا تنافس بعد الملكية — بل تُقرأ
 * لتقرير **كيف يُقال ما يُقال**: جزماً، أو ظنّاً، أو لا يُقال.
 */

import type { Fact } from './types.js';
import type { Request } from './ownership.js';

/* ————— الرتبة ————— */

export type Rank = 'يقين' | 'راجح' | 'ضعيف';

/** ترتيبها عدداً — للمقارنة وحدها، ولا يُعرَض ولا يُرجَّح به. */
export const RANK_ORDER: Record<Rank, number> = { 'ضعيف': 0, 'راجح': 1, 'يقين': 2 };

/** ما تُبنى منه الرتبة: كلُّه معدودٌ أو مرئيّ، ولا واحد منه مجموعٌ موزون. */
export interface Claim {
  /** الحقيقة التي يريد أن يقولها، وnull إن لم يجد شيئاً */
  fact: Fact | null;
  /** أجاء بالتعميم لا بالحفظ؟ التعميمُ ظنٌّ مهما بلغ شبهُه */
  generalized: boolean;
  /** حالُ النزاع على هذا المحمول: من الجُداري لا من حسابٍ هنا */
  dispute: 'لا نزاع' | 'انقضى' | 'قائم';
  /** أرآه بعينه الآن؟ الحاضرُ أقوى من المحفوظ */
  seen: boolean;
}

/**
 * أرضُ الشكّ: دون هذه الثقة تكون الحقيقة قد هُدمت بتصحيحٍ ولم تُبنَ بعد.
 *
 * وهي الرقم الوحيد في هذا الملف، ولا تُقرأ احتمالاً: ثقةُ الجُداري عدّادُ
 * تعزيزٍ يبدأ ٠٫٦ ويُضرَب بـ٠٫٤ عند كل تكذيب. فما دونها محمولٌ كذّبه الأب.
 */
const FRAIL = 0.5;

/**
 * رتبةُ ما يريد أن يقوله.
 *
 * وقد بُنيت أوّلاً على **عدّاد التكرار**، فخرجت لا تُميّز شيئاً: ١١٦ من ١٢٢
 * جملةً في رتبةٍ واحدة، لأن الدرس الواحد لا يبلغ عتبة التكرار أبداً. وتلك هي
 * علّةُ الرقم نفسها منقولةً إلى ثوبٍ جديد — ولو بقيت لكان كلُّ ما يقوله زبير
 * «بظنّي».
 *
 * فبُنيت على **حال البيّنة** لا على عدّها، وهو ما يفعله العاقل:
 *
 *   يقين — قيل له ولم يُنازعه شيء. ودرسُ أبيه الواحد من هذا: هو لا يستنتج
 *          بل ينقل ما سمع، والنقلُ لا يحتاج تكراراً ليصحّ.
 *   راجح — نُوزع ثم استقرّ. أبوه غيّر رأيه فيه مرّةً، وقد يغيّره ثانية،
 *          فيُقال ظنّاً. وهذا موضع «بظنّي» الصحيح: حيث يتردّد العاقل فعلاً.
 *   ضعيف — تعميمٌ، أو نزاعٌ قائم، أو محمولٌ كذّبه الأب فلم يبقَ له سند.
 */
export function rankOf(claim: Claim): Rank {
  if (!claim.fact) return 'ضعيف';
  if (claim.seen) return 'يقين';
  /* والتعميم ظنٌّ مهما بلغ شبهُه: ما لم يُقَل له لا يُنقَل عنه */
  if (claim.generalized) return 'ضعيف';
  if (claim.dispute === 'قائم') return 'ضعيف';
  const c = claim.fact.confidence;
  if (!Number.isFinite(c) || c < FRAIL) return 'ضعيف';
  return claim.dispute === 'انقضى' ? 'راجح' : 'يقين';
}

/* ————— المراجعة: ثلاثُ سلطاتٍ لا رابع ————— */

export type Action =
  | 'أُقرّت'    // يمرّ كما هو
  | 'أُعيدت'   // تُردّ إلى المالك مرّةً واحدة — ولا تعاود
  | 'أُخفضت'   // يُقال ظنّاً لا جزماً
  | 'أُسقطت';  // لا يُقال، ويُقرّ بجهله

export interface Verdict {
  action: Action;
  /** بعبارةٍ واحدة تُكتب في السجلّ ويقرؤها الأب */
  why: string;
}

export interface ReviewInput {
  request: Request;
  rank: Rank;
  claim: Claim;
  /** أطابق وسمُ الجواب وسمَ الطلب؟ يأتي من قانون النوع */
  typeFits: boolean;
  /** أهذه إعادةٌ بعد ردٍّ سابق؟ بها يُمنع التعاود */
  isRedo: boolean;
}

/**
 * مرورٌ واحد، وإعادةٌ واحدة، بلا تعاود.
 *
 * وليست هذه ترجيحاً: لا تختار بين فصّين، ولا تعرف إلا مالكاً واحداً قد تكلّم.
 * عملُها أن تسأل ثلاثة أسئلة بترتيبٍ ثابت — أهذا من نوع ما طُلب؟ أمتينٌ هو؟
 * أيصلح أن يُقال جزماً؟ — وتُخرج واحداً من أربعة.
 *
 * ولا تُستدعى على الملتبس: ذاك جوابه سؤال، ولا دعوى فيه تُراجَع.
 */
export function review(input: ReviewInput): Verdict {
  /* ١) النوع: ما لا يطابق الطلب يُردّ إلى مالكه — مرّةً واحدة. */
  if (!input.typeFits) {
    return input.isRedo
      ? { action: 'أُسقطت', why: 'عاد بغير نوع الطلب بعد الردّ، فلا يُقال' }
      : { action: 'أُعيدت', why: 'نوعُ الجواب غير نوع الطلب — يُردّ إلى مالكه' };
  }

  /* ٢) الفراغ: لا دعوى أصلاً. */
  if (!input.claim.fact) {
    return { action: 'أُسقطت', why: 'لا شيء عند مالكه' };
  }

  /* ٣) الرتبة: بها يُقرَّر كيف يُقال، لا أيُّهما يُقال. */
  switch (input.rank) {
    case 'يقين':
      return { action: 'أُقرّت', why: 'علّمه أبوه وثبتت ولم تُنازَع' };
    case 'راجح':
      /* والراجح يُقال ظنّاً لا جزماً. وهذا ثمنُ ألّا تكون ثقته احتمالاً: من
       * لا يملك رقماً معايَراً لا يجوز أن يتكلّم بلهجة اليقين إلا حيث الرتبة
       * أعلاها. */
      return { action: 'أُخفضت', why: 'راجحةٌ لا يقين — تُقال ظنّاً' };
    case 'ضعيف':
      return { action: 'أُسقطت', why: 'ضعيفةٌ: تعميمٌ أو منازَعةٌ أو مهدومة' };
  }
}
