/* ————— جدول الملكية —————
 *
 * سبعةُ أعطابٍ أظهرها الامتحان، وأربعةٌ منها عطبٌ واحد. اقرأها معاً:
 *
 *   «وين الكنكارو؟»      ← «الكنكارو حيوان»     طُلب مكان، أُعطي جنس
 *   «شو يعمل الفسطاق؟»   ← «الفسطاق مرنجل»      طُلب فعل، أُعطي جنس
 *   «كيفك»               ← «ما وصلني شي»        طُلب حالُه، أُعطي حدُّ معرفة
 *   «شو المرنجل؟»        ← «هلا، اشتقتلك»       طُلب تعريف، أُعطيت تحية
 *
 * ولا جواب فيها **خاطئ**. كلها أجوبةٌ صحيحة على أسئلةٍ لم تُطرح. فالعطب ليس في
 * المعرفة بل في **من يتكلّم**: فصٌّ يملك شيئاً يملأ فراغَ فصٍّ لا يملك شيئاً.
 *
 * وحَكَمٌ فوق صلاحياتٍ متداخلة لا يحلّ هذا: يصير هو نفسه المكانَ الجديد الذي
 * تُكتب فيه الأسبقيات باليد. فالملكية أولاً:
 *
 *   **لكل نوعِ طلبٍ فصٌّ مالكٌ واحد، والبقيّة تُقدّم أدلّةً لا أحكاماً.**
 *
 * ——— وفوق الجدول ثلاثة قوانين ———
 *
 *  ١) **قانون الفراغ**: جوابُ المالك الفارغ جوابٌ **نهائي**. سُئل عن المكان ولا
 *     مكانَ عنده؟ فالجواب «ما بعرف وين» — ولا يُفتح البابُ لفصٍّ آخر يملك شيئاً
 *     مختلفاً. فالعطب لم يكن جهلَه بالمكان، بل أن جهله صار دعوةً لغيره ليملأ.
 *
 *  ٢) **قانون النوع**: يُرَدّ الجواب آلياً إن لم يطابق وسمُ نوعِه وسمَ الطلب.
 *     مقارنةُ وسمين، لا حكمٌ دلاليّ: رخيصة ولا تُخطئ.
 *
 *  ٣) **قانون الغريزة**: لا تتكلّم الغريزة إلا حين لا طلبَ مستخرَجاً. تُلوّن
 *     النبرة دائماً، ولا تكون الجوابَ أبداً ما دام ثمّة سؤال.
 *
 * وهذا الملف **تصريحٌ لا منطق**: لا حساب فيه ولا عتبة. من أراد أن يعرف من
 * يجيب عمّاذا، قرأ الجدول ولم يقرأ `brain.ts`.
 */

/* ————— نوع الطلب —————
 * مفتاح الجدول هو **نوع الطلب لا الموضوع**. «شو الكنكارو» و«وين الكنكارو»
 * موضوعهما واحد ومالكهما — كان يجب أن يكون — مختلفاً. */
export type Request =
  /* معرفةٌ عن شيءٍ في العالم، وله في الجُداري بنيةٌ يُفهرَس بها */
  | 'جنس'     // شو / ما هذا
  | 'صفة'     // كيف هذا
  | 'فعل'     // شو يعمل هذا
  | 'عدد'     // كم
  | 'ملك'     // لمين
  /* معرفةٌ عن شيء، ولا بنية لها عنده بعد — فالفراغ هو الجواب الصادق */
  | 'مكان'    // وين
  | 'زمان'    // إيمتى
  | 'شخص'     // مين
  | 'تصديق'   // هل
  /* ما لا يملكه أحدٌ في دماغه — لا مالك، ولا يُنتظر أن يظهر مالك */
  | 'سبب'     // ليش: لا سببية في دماغه
  | 'اختيار'  // أي: لا مفاضلة
  | 'رأي'     // شو رأيك: لا رأي
  /* عن نفسه لا عن العالم */
  | 'حال'     // كيفك
  /* أفعالُ كلامٍ لا استفهام */
  | 'تحية'
  | 'تعليم'
  | 'تسمية'
  | 'مدح'
  | 'تصحيح'
  | 'حديث'    // كلامٌ لا يطلب شيئاً — وهنا وحدها تتكلّم الغريزة
  /* ————— المخرج الثالث —————
   *
   * وهذا صفٌّ أُضيف بعد نقدٍ في محلّه: مالكٌ **حتميّ** يصير مُخطئاً حتمياً على
   * المسكوكات. «وين ما تروح» ليست سؤالاً عن مكان، و«كيف بتعمل هالشي» تطلب
   * فعلاً بأداة صفة، و«مين قدك» ليست سؤالاً عن شخص. فليكن للنحو مخرجان
   * محدَّدان ومخرجٌ ثالث: **لم أحدّد الطلب**.
   *
   * ولا يهبط الملتبسُ إلى «حديث» — تلك كانت سلّةَ كل ما فشل استخراجه، فيختبئ
   * الفشل في صفٍّ اسمه «كلامٌ عاديّ». بل يُصرَّح به، ومالكه الحَكَم، وجوابه
   * **سؤالٌ يستوضح** لا ترجيحٌ بين تأويلات. فأرجحُ صوابٍ عند من لا يدري ماذا
   * تريد أن يسأل. */
  | 'مُلتبس';

/* ————— وسم نوع الجواب —————
 * ما يحمله الجوابُ من نوع. والمطابقة في قانون النوع مقارنةُ وسمين لا أكثر. */
export type AnswerKind =
  | 'جنس' | 'صفة' | 'فعل' | 'عدد' | 'ملك'
  | 'مكان' | 'زمان' | 'شخص' | 'تصديق'
  | 'حال' | 'تحية'
  /* ثلاثةٌ يقبلها كل طلب: أن يُقرّ بجهله، أو يسأل، أو يُقرّ بالتلقّي */
  | 'إقرار' | 'سؤال' | 'تلقٍّ';

/** ما يجوز أن يُقال في وجه أي طلبٍ كان: الصدق ليس نوعاً يُردّ. */
export const ALWAYS_ALLOWED: ReadonlySet<AnswerKind> = new Set(['إقرار', 'سؤال', 'تلقٍّ']);

/* ————— الفصوص المالكة ————— */
export type Owner =
  | 'parietal'      // الجُداري: كل معرفةٍ عن العالم، مفهرسةً بعلاقتها
  | 'insula'        // الجزيرة: حالُه هو — وهي وحدها تعرفه
  | 'hypothalamus'  // الوطاء: دوافعه
  | 'limbic'        // الحوفي: التحية والوسم العاطفي
  | 'prefrontal'    // الجبهي: ماذا أفعل حين لا يُطلب مني شيء
  | 'arbiter'       // الحَكَم: حالةُ «لا أعرف ماذا تريد» وحدها
  | null;           // لا مالك — والفراغ هو الجواب، لا فرصةٌ لغيره

export interface Row {
  request: Request;
  /** ما يطلبه، بعبارةٍ تُقرأ */
  ar: string;
  owner: Owner;
  ownerAr: string;
  /** من يُدلي بدليلٍ لا بحكم — أسماء الفصوص كما في الشيفرة */
  evidence: readonly string[];
  /** أنواع الجواب التي يقبلها هذا الطلب — قانون النوع */
  accepts: readonly AnswerKind[];
  /** ما يقوله المالك حين لا يملك — قانون الفراغ */
  voidAr: string;
}

