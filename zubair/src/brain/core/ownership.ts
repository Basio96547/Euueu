/* ————— القانون الثالث: الغريزة ————— */

/**
 * أللغريزة أن تكون الجواب الآن؟ لا، إلا حين لا طلبَ مستخرَجاً.
 *
 * «شو المرنجل؟ ← هلا، اشتقتلك» هو الجذعُ يغلب القشرة: دافعُ الوحشة سبق
 * السؤال. فالتلوين يبقى — النبرة والمشاعر — والجوابُ لا.
 */
export function instinctMaySpeak(request: Request): boolean {
  return request === 'حديث' || request === 'تحية' || request === 'مدح';
}

/* ————— الملتبس ————— */

/**
 * أفشل استخراجُ الطلب؟ عندها لا يُرجَّح بين التأويلات بل يُستوضَح.
 *
 * وهذا ليس تواضعاً بل حساب: التأويلات هنا **ليست دعاوى متنافسة** لأحدها سندٌ
 * أقوى — بل قراءاتٌ لجملةٍ واحدة، وواحدةٌ منها صحيحة والأب وحده يعرف أيّها.
 * فترجيحُ أقواها بناءُ آلةٍ في غير موضعها.
 */
export function mustAskBack(request: Request): boolean {
  return request === 'مُلتبس';
}

/* ————— طباعة الجدول —————
 * ليُقرأ الجدول من غير قراءة الشيفرة: `pnpm ownership`. */
export function formatTable(): string {
  const head = ['الطلب', 'ماذا يطلب', 'مالكه', 'من يُدلي بالدليل'];
  const rows = OWNERSHIP.map((r) => [
    r.request, r.ar, r.ownerAr, r.evidence.length === 0 ? '—' : r.evidence.join(' · '),
  ]);
  const widths = head.map((_, i) => Math.max(
    [...head[i] ?? ''].length,
    ...rows.map((r) => [...(r[i] ?? '')].length),
  ));
  const line = (cells: readonly string[]) =>
    cells.map((c, i) => c.padEnd(widths[i] ?? 0, ' ')).join('  ');
  const out = [line(head), widths.map((w) => '─'.repeat(w)).join('  ')];
  for (const r of rows) out.push(line(r));
  return out.join('\n');
}
