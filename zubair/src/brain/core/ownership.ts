const BY_REQUEST = new Map<Request, Row>(OWNERSHIP.map((row) => [row.request, row]));

export function rowOf(request: Request): Row {
  const row = BY_REQUEST.get(request);
  // كل طلبٍ في الجدول بحكم الأنواع؛ وهذا لأجل الشيفرة لا لأجل حالةٍ متوقَّعة
  if (!row) throw new Error(`طلبٌ بلا صفٍّ في جدول الملكية: ${request}`);
  return row;
}

export function ownerOf(request: Request): Owner {
  return rowOf(request).owner;
}

/* ————— القانون الثاني: النوع ————— */

/**
 * أيصلح جوابٌ بهذا الوسم لطلبٍ بهذا الوسم؟ مقارنةُ وسمين، لا أكثر.
 *
 * والإقرار والسؤال والتلقّي تمرّ دائماً: أن يقول «لا أعرف» صوابٌ في وجه كل
 * سؤال، ومنعُه منه يدفعه إلى اختلاق جواب. وهذا هو أصل الهلوسة لا علاجها.
 */
export function typeFits(request: Request, answer: AnswerKind): boolean {
  if (ALWAYS_ALLOWED.has(answer)) return true;
  return rowOf(request).accepts.includes(answer);
}

/* ————— القانون الأول: الفراغ ————— */

/**
 * هل جوابُ المالك الفارغ نهائي؟ نعم في كل طلبٍ يطلب معرفةً بعينها.
 *
 * والاستثناء الوحيد `'حديث'`: لا طلبَ فيه، فلا فراغَ فيه يُملأ بغير حقّه.
 */
export function voidIsFinal(request: Request): boolean {
  return request !== 'حديث';
}

/** ما يقوله حين لا يملك مالكُه شيئاً — بلسان الطلب لا بلسانٍ عام. */
export function voidAnswer(request: Request): string {
  return rowOf(request).voidAr;
}

