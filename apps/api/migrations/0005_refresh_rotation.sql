-- تدوير رمز التحديث وكشف إعادة استعماله
--
-- كان رمز التحديث يعيش ثلاثين يوماً ولا يُبطَل عند التجديد: `refresh()`
-- يُصدر رمزاً جديداً ويترك القديم صالحاً إلى انتهاء أجله. ونتيجته أن من
-- سرق الرمز — من نسخةٍ احتياطية للمتصفّح، أو سجلٍّ، أو ثغرة XSS — ملك
-- حساب صاحبه شهراً كاملاً.
--
-- وأسوأ من طول المدّة أن السرقة لا تترك أثراً: الضحية تُجدّد رمزها
-- والسارق يُجدّد رمزه، ولا يتعارض الاثنان ولا يشكو أحد. فلا شيء في
-- النظام كلّه يستطيع أن يقول إن حساباً سُرّب.
--
-- فصار لكل جلسة رمزُ تحديثٍ واحد صالح. والتجديد يُبطل ما قبله. واستعمالُ
-- رمزٍ مُبطَل ليس خطأً عابراً: هو الدليل الوحيد على أن نسخةً ثانية تعيش
-- في يدٍ أخرى — فتُبطَل الجلسة كلها ويُخرَج الاثنان. الضحية تدخل ثانيةً
-- برمز هاتفها، والسارق لا يملك هاتفاً يدخل به.
--
-- و`prev_jti` مهلةُ رحمة: لسانان مفتوحان يُجدّدان في اللحظة نفسها، وأحدهما
-- يصل بالرمز الذي دُوِّر قبله بجزءٍ من ثانية. بلا هذه المهلة يُطرد صاحبهما
-- بلا ذنب — وحارسٌ يعضّ من يحرسه لا يُترك يعمل، بل يُطفأ.
--
-- الأعمدة تقبل الفراغ: الجلسات القائمة لا رموز مسجَّلة لها، وتُعامَل
-- معاملة القديم فتُدوَّر عند أول تجديد. فلا أحد يُخرَج بهذا الترحيل.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE "sessions" ADD COLUMN "refresh_jti"    TEXT;
ALTER TABLE "sessions" ADD COLUMN "prev_jti"       TEXT;
ALTER TABLE "sessions" ADD COLUMN "prev_at"        DATETIME;
ALTER TABLE "sessions" ADD COLUMN "revoked_reason" TEXT;

-- التجديد يبحث بالجلسة ورمزها معاً في كل طلب
CREATE INDEX "sessions_refresh_jti_idx" ON "sessions"("refresh_jti");
