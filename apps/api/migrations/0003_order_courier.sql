-- إسناد الطلب إلى مندوب
--
-- لم يكن في جدول الطلبات حقلٌ يقول من يوصّلها. ونتيجته أن واجهة المندوب
-- تُعيد كل طلبات المتجر — باسم كل زبون ورقمه وحيّه ومعلمه — إلى هاتف كل
-- مندوب. وأيّ مندوب يستطيع تحويل حالة أيّ طلب لا طلبه.
--
-- والحقل يقبل الفراغ: الطلب الجديد بلا مندوب حتى يُسنَد أو يُطالِب به
-- مندوبٌ في منطقته. والفهرس على (المندوب، الحالة) لأنه استعلام الشاشة
-- الوحيد: «ما عندي اليوم».
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE "orders" ADD COLUMN "courier_id" TEXT;

CREATE INDEX "orders_courier_id_status_idx" ON "orders"("courier_id", "status");
